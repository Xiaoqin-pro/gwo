#!/usr/bin/env python
"""Paper-ready LaTeX tables from a (optionally merged) batch.

    python experiments/make_tables.py results/<batch> --ref GWO --out paper/rase_gwo/tables

Writes main_rows.tex  : mean(std) error per function and algorithm, with
                        + / - / = marking against the reference (Wilcoxon-Holm)
      summary.tex     : average rank, win/loss counts, CPU time
      latex_numbers.json : scalars consumed by the prose sections
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats


def holm(p):
    p = np.asarray(p, float)
    n = len(p)
    order = np.argsort(p)
    adj = np.empty(n)
    run = 0.0
    for r, i in enumerate(order):
        run = max(run, (n - r) * p[i])
        adj[i] = min(1.0, run)
    return adj


def fmt(v):
    if not np.isfinite(v):
        return "n/a"
    if v == 0:
        return "0"
    e = int(np.floor(np.log10(abs(v))))
    m = v / 10 ** e
    if -2 <= e <= 3:
        return f"{v:.3g}"
    return f"{m:.3f}e{e:+d}".replace("e+", "e")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("batch")
    ap.add_argument("--ref", default="GWO")
    ap.add_argument("--file", default="merged_runs.csv")
    ap.add_argument("--out", required=True)
    ap.add_argument("--order", nargs="*", default=None)
    args = ap.parse_args()
    batch = Path(args.batch)
    src = batch / args.file
    if not src.exists():
        src = batch / "runs.csv"
    df = pd.read_csv(src)
    df = df[df.Status == "ok"]

    algos = args.order or list(dict.fromkeys(df.Algorithm))
    funcs = sorted(df.FunctionID.unique())
    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    mean = df.groupby(["FunctionID", "Algorithm"]).FinalError.mean().unstack().reindex(index=funcs, columns=algos)
    std = df.groupby(["FunctionID", "Algorithm"]).FinalError.std().unstack().reindex(index=funcs, columns=algos)
    ranks = mean.rank(axis=1)
    avg = ranks.mean(axis=0)

    sig = {}
    ref = mean[args.ref]
    for a in algos:
        if a == args.ref:
            continue
        ps, marks = [], []
        for f in funcs:
            x = df[(df.FunctionID == f) & (df.Algorithm == a)].FinalError.values
            y = df[(df.FunctionID == f) & (df.Algorithm == args.ref)].FinalError.values
            if len(x) >= 5 and not np.allclose(x, y):
                try:
                    ps.append(stats.mannwhitneyu(x, y, alternative="two-sided", method="asymptotic", use_continuity=True)[1])
                except Exception:
                    ps.append(1.0)
            else:
                ps.append(1.0)
        adj = holm(ps)
        for i, f in enumerate(funcs):
            if adj[i] >= 0.05:
                marks.append("$\\approx$")
            elif mean.loc[f, a] < ref[f]:
                marks.append("$+$")
            else:
                marks.append("$-$")
        sig[a] = (np.array(adj), marks)

    # main table
    lines = ["% generated by experiments/make_tables.py", "\\begin{tabular}{l" + "c" * len(algos) + "}", "\\toprule",
             " & ".join(["F"] + [a.replace("Over", "O").replace("-", "-") for a in algos]) + " \\\\", "\\midrule"]
    for f in funcs:
        cells = []
        for a in algos:
            m, s = mean.loc[f, a], std.loc[f, a]
            mark = "" if a == args.ref else sig[a][1][funcs.index(f)]
            cells.append(f"{fmt(m)}({fmt(s)}){mark}")
        lines.append(f"F{f} & " + " & ".join(cells) + " \\\\")
    wlt = {a: [0, 0] for a in algos}
    for a in algos:
        if a == args.ref:
            continue
        for f in funcs:
            if mean.loc[f, a] < ref[f]:
                wlt[a][0] += 1
            elif mean.loc[f, a] > ref[f]:
                wlt[a][1] += 1
    lines.append("\\midrule")
    lines.append("w/t/l vs " + args.ref + " & " + " & ".join(
        ["--"] + [f"{wlt[a][0]}/{wlt[a][1]}" if a != args.ref else "--" for a in algos]) + " \\\\")
    lines.append("avg. rank & " + " & ".join([f"{avg[a]:.2f}" for a in algos]) + " \\\\")
    lines.append("mean CPU (s) & " + " & ".join(
        [f"{df[df.Algorithm == a].Seconds.mean():.2f}" for a in algos]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (outdir / "main_rows.tex").write_text("\n".join(lines), encoding="utf-8")

    # summary
    sl = ["\\begin{tabular}{lrrrr}", "\\toprule",
          "Algorithm & Avg. rank & fn w/l & mean CPU (s) & mean FE \\\\", "\\midrule"]
    for a in avg.sort_values().index:
        w, l = wlt.get(a, ["--", "--"])
        sl.append(f"{a} & {avg[a]:.3f} & {w}/{l} & "
                  f"{df[df.Algorithm == a].Seconds.mean():.2f} & "
                  f"{df[df.Algorithm == a].Evaluations.mean():.0f} \\\\")
    sl += ["\\bottomrule", "\\end{tabular}"]
    (outdir / "summary.tex").write_text("\n".join(sl), encoding="utf-8")

    chi2, fp = (stats.friedmanchisquare(*[mean[a].values for a in algos])
                if len(algos) > 2 else (np.nan, np.nan))
    nums = {
        "n_functions": len(funcs), "n_algorithms": len(algos),
        "friedman_chi2": float(chi2), "friedman_p": float(fp),
        "avg_rank": {a: float(avg[a]) for a in algos},
        "fn_wins_vs_ref": {a: int(wlt[a][0]) for a in wlt},
        "fn_losses_vs_ref": {a: int(wlt[a][1]) for a in wlt},
        "mean_cpu": {a: float(df[df.Algorithm == a].Seconds.mean()) for a in algos},
        "median_error_ratio_vs_ref": {
            a: float(np.exp(np.median(np.log((mean[a].values + 1e-30) / (ref.values + 1e-30)))))
            for a in algos},
    }
    (outdir / "latex_numbers.json").write_text(json.dumps(nums, indent=2), encoding="utf-8")
    print(f"tables -> {outdir}")
    print(json.dumps(nums["avg_rank"], indent=2))


if __name__ == "__main__":
    main()
