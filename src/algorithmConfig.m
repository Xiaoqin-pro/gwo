                             'K',12,'screenPolicy','geometry','divCriterion','minority','convShare',0.9));
    case 'RASE-IGWO-K12r',cfg=struct('f',@IGWO,'N',50,'state',struct('evalPolicy','screen', ...
                             'K',12,'screenPolicy','random','convShare',0.9));
    case 'RASE-IGWO-K6', cfg=struct('f',@IGWO,'N',50,'state',struct('evalPolicy','screen', ...
                             'K',6,'screenPolicy','geometry','divCriterion','minority','convShare',0.9));
    case 'RASE-IGWO-K6r',cfg=struct('f',@IGWO,'N',50,'state',struct('evalPolicy','screen', ...
                             'K',6,'screenPolicy','random','convShare',0.9));
    case 'VS-DLH-A1',    cfg=struct('f',@IGWO,'N',50,'state',struct('evalPolicy','full', ...
                             'successGuide',0.25,'successFrac',0.25));
    case 'VS-DLH-A3',    cfg=struct('f',@IGWO,'N',50,'state',struct('evalPolicy','screen', ...
                             'K',25,'screenPolicy','geometry','divCriterion','minority','convShare',0.9, ...
