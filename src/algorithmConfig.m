        'qEpsStart',0.10,'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'Over1000-90g', cfg=rwo(1000,0.9,struct('driftGate',true));
    case 'Over1000-90ld',cfg=rwo(1000,0.9,struct('divCriterion','leaders'));
    case 'Over1000-90min',cfg=rwo(1000,0.9,struct('divCriterion','minority'));
    case 'Over1000-80min',cfg=rwo(1000,0.8,struct('divCriterion','minority'));
    case 'Over1000-70min',cfg=rwo(1000,0.7,struct('divCriterion','minority'));
    case 'Fixed55min',   cfg=rwo(1000,0.5,struct('divCriterion','minority'));
    case 'Over1000-90nv',cfg=rwo(1000,0.9,struct('useVirtual',false,'divCriterion','minority'));
    case 'Over1000-90q3',cfg=rwo(1000,0.9,struct('quotaPolicy','q','divCriterion','minority', ...
        'convShares',[0.7 0.9 1.0],'qEpsStart',0.10,'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'Over500-90',   cfg=rwo(500,0.9);
    case 'Over250-90r',  cfg=rwo(250,0.9,struct('screenPolicy','random'));
    case 'Over250-90nv', cfg=rwo(250,0.9,struct('useVirtual',false,'divCriterion','minority'));
    case 'Over250-90q',  cfg=rwo(250,0.9,struct('quotaPolicy','q'));
    % ---- sparse-budget family (legacy protocol: 10 evals per round) -----
    case 'Sparse50-55',  cfg=rsp(0.5);
    case 'Sparse50-90',  cfg=rsp(0.9);
    case 'Sparse50-Q',   cfg=rsp(0.9,struct('quotaPolicy','q'));
    % ---- performance round 1 (2026-10-16): structural fixes ----
    case 'Best90min',    cfg=rwo(1000,0.9,struct('verifiedMode','best','divCriterion','minority'));
    case 'Elite90q3',    cfg=rwo(1000,0.9,struct('eliteAnchor',true,'divCriterion','minority', ...
                             'quotaPolicy','q','convShares',[0.7 0.9 1.0],'qEpsStart',0.10, ...
                             'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'BestElite-q3', cfg=rwo(1000,0.9,struct('eliteAnchor',true,'verifiedMode','best', ...
                             'divCriterion','minority','quotaPolicy','q','convShares',[0.7 0.9 1.0], ...
                             'qEpsStart',0.10,'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'Best90q3',     cfg=rwo(1000,0.9,struct('verifiedMode','best','divCriterion','minority', ...
                             'quotaPolicy','q','convShares',[0.7 0.9 1.0],'qEpsStart',0.10, ...
                             'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'Micro4-90q3',  cfg=rwo(1000,0.9,struct('microBatches',4,'divCriterion','minority', ...
                             'quotaPolicy','q','convShares',[0.7 0.9 1.0],'qEpsStart',0.10, ...
                             'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'Micro10-90q3', cfg=rwo(1000,0.9,struct('microBatches',10,'divCriterion','minority', ...
                             'quotaPolicy','q','convShares',[0.7 0.9 1.0],'qEpsStart',0.10, ...
                             'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'BestMicro4-q3',cfg=rwo(1000,0.9,struct('microBatches',4,'verifiedMode','best', ...
                             'divCriterion','minority','quotaPolicy','q','convShares',[0.7 0.9 1.0], ...
                             'qEpsStart',0.10,'qEpsEnd',0.02,'windowFE',2000,'qInit',true));
    case 'Knn-Mix50q',    cfg=rwo(1000,0.9,struct('refinePolicy','knn','refinePool',4,'knnE',10, ...
                             'mixFrac',0.5,'familyPolicy','q','familyShares',[0.9 0.7 0.5], ...
                             'eliteAnchor',true,'divCriterion','minority','quotaPolicy','q', ...
                             'convShares',[0.7 0.9 1.0],'qEpsStart',0.10,'qEpsEnd',0.02, ...
                             'windowFE',2000,'qInit',true));
    case 'Knn-Elite90q3',cfg=rwo(1000,0.9,struct('refinePolicy','knn','refinePool',4,'knnE',10, ...
                             'eliteAnchor',true,'divCriterion','minority','quotaPolicy','q', ...
                             'convShares',[0.7 0.9 1.0],'qEpsStart',0.10,'qEpsEnd',0.02, ...
                             'windowFE',2000,'qInit',true));
    case 'Mix20-90',      cfg=rwo(1000,0.9,struct('mixFrac',0.2,'familyShare',0.9, ...
                             'eliteAnchor',true,'divCriterion','minority','quotaPolicy','q', ...
                             'convShares',[0.7 0.9 1.0],'qEpsStart',0.10,'qEpsEnd',0.02, ...
