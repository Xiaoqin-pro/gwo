function [Best,T,info]=GWO(f,state,~,N,seed)
%GWO  Canonical Grey Wolf Optimizer (Mirjalili, Mirjalili & Lewis, 2014).
%
%   [Best,T,info]=GWO(f,state,[],N,seed)
%
% Full-evaluation baseline of the RASE-GWO study.  The search equations, the
% leadership hierarchy and the evaluation order follow the published
% algorithm: every wolf is moved once per generation in index order, each new
% position is evaluated immediately, and alpha/beta/delta are refreshed right
% after every true evaluation.
%
% The file uses the CEC harness interface of this project:
%   state.initialPopulation  N-by-D starting positions (caller-controlled RNG)
%   state.lowerBound        1-by-D
%   state.upperBound        1-by-D
%   state.maxEvaluations    total TRUE evaluations, initialization included
% Outputs:
%   Best.Cost / Best.Vector  best true fitness found and its position
%   T                        budget-by-1 record, T(fe) = best after fe evals
%   info.Evaluations         true evaluations consumed (== budget unless the
%                            budget is smaller than the population)
%   info.Rounds              number of completed generations
%   info.MeanEvalsPerRound   budget / Rounds
%
% Randomness: rng(seed,'twister') drives the search stream.  The initial
% population is generated by the caller from a different seed.

pop=state.initialPopulation;
[N0,D]=size(pop);
assert(N0==N,'Population size mismatch: state holds %d rows, N=%d.',N0,N);
lb=state.lowerBound; ub=state.upperBound; budget=state.maxEvaluations;
assert(numel(lb)==D && numel(ub)==D,'Bound vectors must match D=%d.',D);
assert(budget>=N && budget==floor(budget),'Budget must be an integer >= N.');
assert(all(isfinite(pop),'all') && all(pop>=lb & pop<=ub,'all'), ...
    'Initial population must be finite and inside the bounds.');
randMode='dim';
if isfield(state,'randMode'), randMode=state.randMode; end
rng(seed,'twister');
clockStart=tic;

X=pop;
T=nan(budget,1);
Alpha=struct('Cost',inf,'Vector',zeros(1,D));
Beta=Alpha; Delta=Alpha;
fe=0;
for i=1:N
    v=f(X(i,:));
    fe=fe+1;
    [Alpha,Beta,Delta]=insertLeader(Alpha,Beta,Delta,X(i,:),v);
    T(fe)=Alpha.Cost;
end
rounds=0;

% ===================== main loop =====================
while fe<budget
    rounds=rounds+1;
    aC=2-2*(fe/budget);                       % Mirjalili's linear decay 2 -> 0
    for i=1:N
        if fe>=budget, break; end
        if strcmp(randMode,'wolf')
            A1=2*aC*rand()-aC; C1=2*rand();
            A2=2*aC*rand()-aC; C2=2*rand();
            A3=2*aC*rand()-aC; C3=2*rand();
        else
            A1=2*aC*rand(1,D)-aC; C1=2*rand(1,D);
            A2=2*aC*rand(1,D)-aC; C2=2*rand(1,D);
            A3=2*aC*rand(1,D)-aC; C3=2*rand(1,D);
        end
        X1=Alpha.Vector-A1.*abs(C1.*Alpha.Vector-X(i,:));
        X2=Beta.Vector -A2.*abs(C2.*Beta.Vector -X(i,:));
        X3=Delta.Vector-A3.*abs(C3.*Delta.Vector-X(i,:));
        Xn=(X1+X2+X3)/3;
        Xn=max(min(Xn,ub),lb);
        X(i,:)=Xn;
        v=f(Xn);
        fe=fe+1;
        [Alpha,Beta,Delta]=insertLeader(Alpha,Beta,Delta,Xn,v);
        T(fe)=Alpha.Cost;
    end
end

Best.Cost=Alpha.Cost;
Best.Vector=Alpha.Vector;
info.Evaluations=fe;
info.Rounds=rounds;
info.MeanEvalsPerRound=fe/max(rounds,1);
info.WallClock=toc(clockStart);
info.Algorithm='GWO';
end

% ===================== helpers =====================
function [A,B,Dl]=insertLeader(A,B,Dl,x,v)
if v<A.Cost
    Dl=B; B=A; A=struct('Cost',v,'Vector',x);
elseif v<B.Cost
    Dl=B; B=struct('Cost',v,'Vector',x);
elseif v<Dl.Cost
    Dl=struct('Cost',v,'Vector',x);
end
end
